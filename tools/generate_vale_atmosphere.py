"""Stage 2.5a: voxel mushrooms, measured frequencies and biome music resources.
Run after older Vale generators. Does not rewrite cottages, lanterns or benches.
"""
from pathlib import Path
import json
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'src/main/resources'
ASSETS = RES / 'assets/dudunka'
DATA = RES / 'data/dudunka/worldgen'
JAVA = ROOT / 'src/main/java/io/github/golovinss/dudunka'


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + '\n')


def box(lo, hi, texture):
    return {'from': lo, 'to': hi, 'faces': {face: {'texture': '#' + texture, 'uv': [0, 0, 16, 16]}
            for face in ['north', 'south', 'east', 'west', 'up', 'down']}}


# Each cap layer is assembled on a circular footprint. Fine ribs, raised luminous
# spots and quarter-block rim steps provide detail within the terrain block grid.
cap = {
    0: [box([0, 12, 0], [16, 16, 16], 'gill')] +
       [box([n, 8, 0], [n+1, 12, 16], 'gill') for n in [1, 4, 7, 10, 13]],
    1: [box([0, 0, 0], [16, 4, 16], 'gill'), box([0, 4, 0], [16, 14, 16], 'cap'),
        box([2, 14, 3], [5, 16, 6], 'glow'), box([10, 14, 9], [13, 16, 12], 'glow')],
    2: [box([0, 0, 0], [16, 8, 16], 'cap'), box([1, 8, 1], [15, 12, 15], 'cap'),
        box([3, 12, 3], [13, 16, 13], 'cap'), box([4, 12, 1], [7, 14, 3], 'glow')],
    4: [box([7, 12, 7], [9, 16, 9], 'gill'), box([6, 10, 6], [10, 12, 10], 'cap'),
        box([5, 3, 5], [11, 10, 11], 'glow'), box([6, 0, 6], [10, 3, 10], 'glow')],
    3: [box([0, 0, 0], [16, 4, 16], 'cap'), box([2, 4, 2], [14, 8, 14], 'cap'),
        box([5, 8, 5], [11, 10, 11], 'glow')],
}
stem = {}
for profile, width in enumerate([14, 8, 12, 10]):
    edge = (16-width)//2
    stem[profile] = [box([edge, 0, edge], [16-edge, 16, 16-edge], 'cap'),
                     box([edge-1, 0, 6], [edge, 16, 10], 'gill'),
                     box([16-edge, 0, 6], [17-edge, 16, 10], 'gill'),
                     box([6, 0, edge-1], [10, 16, edge], 'gill'),
                     box([6, 0, 16-edge], [10, 16, 17-edge], 'gill')]
stem[4] = stem[3]
# Small original pixel palettes use coherent flecks/veins, rather than white
# per-pixel noise. These new assets leave all earlier textures untouched.
palettes = {
    'turquoise': ((15,132,151), (22,164,177), (37,194,200), (164,255,246)),
    'violet': ((91,43,151), (116,58,177), (146,80,198), (244,173,255)),
    'golden': ((205,137,31), (227,166,42), (246,197,67), (255,246,165)),
}
for color,(dark,base,high,glow) in palettes.items():
    im = Image.new('RGB',(16,16),base);draw = ImageDraw.Draw(im)
    for x,y,w in [(1,2,3),(8,0,4),(5,8,3),(12,11,3),(0,14,4)]:
        draw.rectangle((x,y,min(15,x+w),min(15,y+1)),fill=dark)
    for x,y in [(3,5),(10,4),(7,12),(14,8)]:
        draw.line((x,y,min(15,x+2),y),fill=high)
    im.save(ASSETS / f'textures/block/{color}_landmark_cap.png')
    im = Image.new('RGB',(16,16),glow);draw=ImageDraw.Draw(im)
    draw.line((0,0,0,15),fill=high);draw.line((1,0,14,0),fill=high)
    draw.line((3,2,3,12),fill=tuple(min(255,c+12) for c in glow))
    im.save(ASSETS / f'textures/block/{color}_landmark_glow.png')
parts = ['turquoise_landmark_cap', 'violet_landmark_cap', 'golden_landmark_cap', 'vale_landmark_stem']
for name in parts:
    is_stem = name.endswith('stem')
    color = name.split('_')[0]
    textures = {'cap': 'dudunka:block/' + ('vale_mushroom_stem' if is_stem else color + '_landmark_cap'),
                'gill': 'dudunka:block/vale_mushroom_inside',
                'glow': 'dudunka:block/' + ('vale_decor_cream' if is_stem else color + '_landmark_glow')}
    textures['particle'] = textures['cap']
    for profile, elements in (stem if is_stem else cap).items():
        write(ASSETS / f'models/block/{name}_{profile}.json', {'textures': textures, 'elements': elements})
    write(ASSETS / f'blockstates/{name}.json', {'variants': {f'profile={n}': {'model': f'dudunka:block/{name}_{n}'} for n in range(5)}})
    write(ASSETS / f'models/item/{name}.json', {'parent': f'dudunka:block/{name}_1'})
    write(RES / f'data/dudunka/loot_tables/blocks/{name}.json', {'type': 'minecraft:block', 'pools': [{
        'rolls': 1, 'conditions': [{'condition': 'minecraft:survives_explosion'}],
        'entries': [{'type': 'minecraft:item', 'name': 'dudunka:' + name}]}]})

lines = ['package io.github.golovinss.dudunka;', '', '/** Generated by tools/generate_vale_atmosphere.py from model cuboids. */',
         'final class MushroomValeLandmarkShapes {', '    static double[][] boxes(String id, int profile) {',
         '        boolean stem = id.equals("vale_landmark_stem");', '        if (stem) return switch (profile) {']
for shapes in [stem, cap]:
    for profile, elements in shapes.items():
        boxes = ', '.join('{' + ','.join(str(n) for n in e['from'] + e['to']) + '}' for e in elements)
        lines.append(f'            case {profile} -> new double[][]{{{boxes}}};')
    lines += ['            default -> throw new IllegalArgumentException("profile");', '        };']
    if shapes is stem:
        lines += ['        return switch (profile) {']
lines += ['    }', '    private MushroomValeLandmarkShapes() {}', '}']
(JAVA / 'MushroomValeLandmarkShapes.java').write_text('\n'.join(lines) + '\n')

for color in ['turquoise', 'violet', 'golden']:
    pieces = []
    def add(x,y,z,name,profile):
        pieces.append({'offset': [x,y,z], 'state': {'Name': 'dudunka:' + name, 'Properties': {'profile': str(profile)}}})
    for y in range(5):
        add(0,y,0,'vale_landmark_stem', 0 if y == 0 else 2 if y == 4 else 1)
    layers = [(4,3,0),(5,4,1),(6,3,2),(7,2,2),(8,1,3)]
    if color == 'violet': layers += [(9,0,3)]
    for y,radius,profile in layers:
        for x in range(-radius,radius+1):
            for z in range(-radius,radius+1):
                if x*x+z*z <= radius*radius and not (y == 4 and x == z == 0):
                    add(x,y,z,color + '_landmark_cap',4 if y == 4 and abs(x) == 2 and abs(z) == 1 else profile)
    write(DATA / f'configured_feature/mushroom_vale/{color}_landmark.json', {
        'type': 'dudunka:mushroom_vale_landmark', 'config': {'radius': 4, 'height': 10 if color == 'violet' else 9, 'blocks': pieces}})

# More discoverable, seven-wide detailed mushrooms use the same approved voxel
# parts. Nine-wide landmark feature IDs retain a separate uncommon size class.
for color in ['turquoise', 'violet', 'golden']:
    pieces = []
    for y in range(4):
        pieces.append({'offset':[0,y,0], 'state':{'Name':'dudunka:vale_landmark_stem', 'Properties':{'profile':str(0 if y==0 else 2 if y==3 else 1)}}})
    for y,radius,profile in [(3,2,0),(4,3,1),(5,2,2),(6,1,3)]:
        for x in range(-radius,radius+1):
            for z in range(-radius,radius+1):
                if x*x+z*z<=radius*radius and not (y==3 and x==z==0):
                    pieces.append({'offset':[x,y,z], 'state':{'Name':f'dudunka:{color}_landmark_cap',
                        'Properties':{'profile':str(4 if y==3 and abs(x)==abs(z)==1 else profile)}}})
    write(DATA / f'configured_feature/mushroom_vale/giant_{color}.json', {
        'type':'dudunka:mushroom_vale_landmark', 'config':{'radius':3, 'height':7, 'blocks':pieces}})

for name,chance in {'giant_red':6, 'giant_brown':8, 'giant_turquoise':4, 'giant_violet':4,
                    'giant_golden':6, 'turquoise_landmark':48, 'violet_landmark':56, 'golden_landmark':96,
                    'bench':8}.items():
    p=DATA / f'placed_feature/mushroom_vale/{name}.json'
    value=json.loads(p.read_text()); value['placement'][0]={'type':'minecraft:rarity_filter','chance':chance}; write(p,value)
for mood in ['glowing','memory','pink']:
    p=DATA / f'configured_feature/mushroom_vale/{mood}_small_mushrooms.json'
    value=json.loads(p.read_text());value['config']['tries']=24 if mood=='pink' else 32
    entries=value['config']['feature']['feature']['config']['to_place']['entries']
    entries[:]=[e for e in entries if not e['data']['Name'].startswith('minecraft:')]
    entries += [{'data':{'Name':'minecraft:'+color+'_mushroom'},'weight':4} for color in ['red','brown']]
    write(p,value)

for p in (DATA / 'biome').glob('*.json'):
    value=json.loads(p.read_text())
    if p.stem == 'pink_meadows':
        refs=value['features'][9]
        for name in ['giant_red','giant_brown']:
            identifier='dudunka:mushroom_vale/'+name
            if identifier not in refs: refs.insert(refs.index('dudunka:mushroom_vale/giant_golden'), identifier)
    value['effects']['music']={
        'sound':'dudunka:music.mushroom_vale_theme', 'min_delay':1200, 'max_delay':3600, 'replace_current_music':True};write(p,value)
p=ASSETS/'sounds.json'
sounds=json.loads(p.read_text()) if p.exists() else {}
sounds['music.mushroom_vale_theme']={'sounds':[{'name':'dudunka:music/mushroom_vale_theme','stream':True}]};write(p,sounds)
for lang,labels in [('en_us',['Turquoise Landmark Cap','Violet Landmark Cap','Golden Landmark Cap','Fluted Landmark Stem']),
                    ('ru_ru',['Бирюзовая шляпка гриба-великана','Фиолетовая шляпка гриба-великана','Золотистая шляпка гриба-великана','Ребристая ножка гриба-великана'])]:
    p=ASSETS/f'lang/{lang}.json';value=json.loads(p.read_text());value.update({'block.dudunka.'+name:label for name,label in zip(parts,labels)});write(p,value)
print('Stage 2.5a: four voxel parts, three landmarks, discoverable mushrooms, benches and streamed biome music.')
